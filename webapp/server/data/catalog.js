function m(id, type, title, year, rating, genres, overview, extra = {}) {
  const cast = extra.cast && extra.cast.length ? extra.cast : ['Cast'];
  return {
    id,
    mediaType: type,
    title,
    year,
    rating,
    votes: extra.votes ?? Math.round(rating * 11000 + (id % 7) * 3400),
    genres,
    genreNames: genres.map((g) => GENRES[g]).filter(Boolean),
    overview,
    runtime: extra.runtime ?? (type === 'tv' ? 42 : 105 + ((id * 7) % 45)),
    tagline: extra.tagline || '',
    cast,
    director: extra.director || cast[0],
    seasons: extra.seasons || null,
    episodes: extra.episodes || null,
    popularity: extra.popularity ?? 100 - (id % 88),
    addedAt: extra.addedAt || `2026-0${1 + (id % 9)}-1${id % 9}`,
    colors: extra.colors || null,
    art: artFor(genres),
    artPos: `${(id * 37) % 100}% ${(id * 61) % 100}%`,
    source: 'catalog',
  };
}

